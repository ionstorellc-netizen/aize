import { useState, useEffect } from 'react'
import { useSearchParams, useNavigate } from 'react-router-dom'
import { api, act, useApi, Badge, CATEGORIES, useJob, Modal } from '../lib.jsx'
import NewProject from './NewProject.jsx'

export default function Ideas() {
  const [sp] = useSearchParams()
  const nav = useNavigate()
  const [cat, setCat] = useState('')
  const [status, setStatus] = useState('')
  const q = `/ideas?${cat ? 'category=' + encodeURIComponent(cat) + '&' : ''}${status ? 'status=' + status : ''}`
  const ideas = useApi(q, [q])
  const runs = useApi('/research')
  const [gen, setGen] = useState({ topic: '', research_run_id: '', category: '' })
  const [manual, setManual] = useState(false)
  const [mf, setMf] = useState({ title: '', category: 'Amazon', topic: '', viral_hook: '' })
  const [proj, setProj] = useState(null)
  const job = useJob(() => ideas.reload())
  useEffect(() => { if (sp.get('job')) job.start(+sp.get('job')) }, [])
  const generate = async () => {
    const r = await act(() => api('/ideas/generate', { method: 'POST', body: { ...gen, research_run_id: gen.research_run_id ? +gen.research_run_id : null, category: gen.category || null } }), 'Generating ideas…')
    job.start(r.job_id)
  }
  const setS = async (id, s) => { await api('/ideas/' + id, { method: 'PATCH', body: { status: s } }); ideas.reload() }
  const script = async i => { const r = await act(() => api('/scripts/generate', { method: 'POST', body: { idea_id: i.id } }), 'Writing script…'); nav('/scripts?job=' + r.job_id) }
  return <div className="page">
    <div className="head"><div><h1>Content <em>Ideas</em></h1><p>Ideas are generated by Claude from your verified research. Approve, reject or save them, then turn one into a script or a full project.</p></div>
      <button className="btn" onClick={() => setManual(true)}>Add idea manually</button></div>
    <div className="card" style={{ marginBottom: 16 }}>
      <div className="grid g4" style={{ alignItems: 'end' }}>
        <div><label>Topic (optional)</label><input value={gen.topic} onChange={e => setGen({ ...gen, topic: e.target.value })} placeholder="e.g. Amazon Saudi beginners" /></div>
        <div><label>From research run</label><select value={gen.research_run_id} onChange={e => setGen({ ...gen, research_run_id: e.target.value })}><option value="">— none</option>{(runs.data || []).filter(r => r.status === 'done').map(r => <option key={r.id} value={r.id}>#{r.id} {r.query || r.categories.join(', ')}</option>)}</select></div>
        <div><label>Category</label><select value={gen.category} onChange={e => setGen({ ...gen, category: e.target.value })}><option value="">Any</option>{CATEGORIES.map(c => <option key={c}>{c}</option>)}</select></div>
        <button className="btn primary" disabled={job.running} onClick={generate}>{job.running ? 'Generating…' : 'Generate 10 ideas'}</button>
      </div>
    </div>
    <div className="row" style={{ marginBottom: 14 }}>
      <button className={'chip ' + (!cat ? 'on' : '')} onClick={() => setCat('')}>All</button>
      {CATEGORIES.map(c => <button key={c} className={'chip ' + (cat === c ? 'on' : '')} onClick={() => setCat(c)}>{c}</button>)}
      <span style={{ width: 20 }} />
      {['', 'new', 'approved', 'saved', 'rejected', 'used'].map(s => <button key={s} className={'chip ' + (status === s ? 'on' : '')} onClick={() => setStatus(s)}>{s || 'any status'}</button>)}
    </div>
    {(ideas.data || []).length === 0 ? <div className="empty">No ideas here yet.</div> :
      <div className="grid g3">{ideas.data.map(i => { const d = i.data || {}; return <div className="card col" key={i.id}>
        <div className="row between"><Badge>{i.category}</Badge><Badge s={i.status} /></div>
        <h2 style={{ margin: 0 }}>{i.title}</h2>
        {d.viral_hook && <div className="serif gold" style={{ fontSize: 20, fontStyle: 'italic' }}>“{d.viral_hook}”</div>}
        {d.why_it_matters && <div className="small muted">{d.why_it_matters}</div>}
        {d.talking_points?.length > 0 && <ul className="small" style={{ paddingLeft: 18, margin: 0 }}>{d.talking_points.map((t, k) => <li key={k}>{t}</li>)}</ul>}
        <div className="small dim">{d.target_audience} {d.estimated_duration_s ? `· ~${d.estimated_duration_s}s` : ''}</div>
        {d.suggested_visuals?.length > 0 && <div className="small"><span className="dim">Visuals:</span> {d.suggested_visuals.join(', ')}</div>}
        {d.cta && <div className="small"><span className="dim">CTA:</span> {d.cta}</div>}
        {d.competitor_inspiration_urls?.length > 0 && <div className="small">Inspiration: {d.competitor_inspiration_urls.map((u, k) => <a key={k} href={u} target="_blank" style={{ marginRight: 8 }}>source {k + 1}</a>)}</div>}
        <div className="row" style={{ marginTop: 'auto' }}>
          <button className="btn sm green" onClick={() => setS(i.id, 'approved')}>Approve</button>
          <button className="btn sm" onClick={() => setS(i.id, 'saved')}>Save</button>
          <button className="btn sm danger" onClick={() => setS(i.id, 'rejected')}>Reject</button>
          <button className="btn sm" onClick={() => script(i)}>Write script</button>
          <button className="btn sm primary" onClick={() => setProj(i)}>Make video</button>
        </div></div> })}</div>}
    {manual && <Modal title="Add idea" onClose={() => setManual(false)}>
      <div className="field"><label>Title</label><input value={mf.title} onChange={e => setMf({ ...mf, title: e.target.value })} /></div>
      <div className="field"><label>Category</label><select value={mf.category} onChange={e => setMf({ ...mf, category: e.target.value })}>{CATEGORIES.map(c => <option key={c}>{c}</option>)}</select></div>
      <div className="field"><label>Topic</label><textarea value={mf.topic} onChange={e => setMf({ ...mf, topic: e.target.value })} /></div>
      <div className="field"><label>Hook</label><input value={mf.viral_hook} onChange={e => setMf({ ...mf, viral_hook: e.target.value })} /></div>
      <button className="btn primary" disabled={!mf.title} onClick={async () => { await api('/ideas', { method: 'POST', body: mf }); setManual(false); ideas.reload() }}>Save</button>
    </Modal>}
    {proj && <NewProject preset={{ title: proj.title, topic: proj.data?.topic || proj.title, category: proj.category, idea_id: String(proj.id) }} onClose={() => setProj(null)} onCreated={id => nav('/queue/' + id)} />}
  </div>
}
